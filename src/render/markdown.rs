    /// Column at which the text after the list marker starts on the first line.
    fn first_text_column(line: &str) -> usize {
        let marker_end = line.find("\x1b[0m ").expect("marker") + "\x1b[0m ".len();
        visible_len(&line[..marker_end])
    }

