/// Parse and render a markdown document to an ANSI string.
pub fn render_document(markdown: &str, base_dir: Option<&Path>, config: &Config) -> Result<String> {
    let arena = Arena::new();
    let mut options = Options::default();
    options.extension.strikethrough = true;
    options.extension.table = true;
    options.extension.autolink = true;
    options.extension.tasklist = true;
    options.extension.footnotes = true;
    options.extension.front_matter_delimiter = Some("---".to_owned());

    // Escape sequences are generated by the renderer only, never taken from the document.
    let markdown = sanitize_control_chars(markdown);
    let root = parse_document(&arena, &markdown, &options);

    let mut output = String::new();
    render_node(root, &mut output, base_dir, config, 0, false)?;
    Ok(output)
}

fn render_node<'a>(
    node: &'a AstNode<'a>,
    output: &mut String,
    base_dir: Option<&Path>,
    config: &Config,
    indent: usize,
    in_tight_list: bool,
) -> Result<()> {
    let data = node.data.borrow();

    match &data.value {
        NodeValue::Document => {
            drop(data);
            for child in node.children() {
                render_node(child, output, base_dir, config, indent, false)?;
            }
        }

        NodeValue::Heading(NodeHeading { level, .. }) => {
            let level = *level;
            drop(data);

            let mut text = String::new();
            collect_text(node, &mut text);
            // Inside a list item, stay within the item's indent like other blocks.
            let width = (config.width as usize).saturating_sub(indent);
            let pad = " ".repeat(indent);

            match level {
                1 => {
                    let line = "═".repeat(width.min(display_width(&text) + 4));
                    output.push_str(&format!("\n{pad}\x1b[1;34m{line}\x1b[0m\n"));
                    output.push_str(&format!("{pad}\x1b[1;34m  {text}\x1b[0m\n"));
                    output.push_str(&format!("{pad}\x1b[1;34m{line}\x1b[0m\n\n"));
                }
                2 => {
                    let line = "─".repeat(width.min(display_width(&text) + 2));
                    output.push_str(&format!("\n{pad}\x1b[1;36m{text}\x1b[0m\n"));
                    output.push_str(&format!("{pad}\x1b[36m{line}\x1b[0m\n\n"));
                }
                3 => output.push_str(&format!("\n{pad}\x1b[1;33m### {text}\x1b[0m\n\n")),
                4 => output.push_str(&format!("\n{pad}\x1b[1m#### {text}\x1b[0m\n\n")),
                _ => output.push_str(&format!("\n{pad}\x1b[1m{text}\x1b[0m\n\n")),
            }
        }

        NodeValue::Paragraph => {
            drop(data);
            let mut inline_out = String::new();
            for child in node.children() {
                render_inline(child, &mut inline_out, base_dir, config)?;
            }
            let prefix = " ".repeat(indent);
            let wrapped = word_wrap(&inline_out, config.width as usize, indent);
            output.push_str(&format!("{prefix}{wrapped}\n"));
            if !in_tight_list {
                output.push('\n');
            }
        }

        NodeValue::BlockQuote => {
            drop(data);
            let mut inner = String::new();
            // The indent and the "│ " prefix take columns; wrap the contents narrower to compensate.
            let mut inner_config = config.clone();
            inner_config.width = config.width.saturating_sub(indent as u16 + 2);
            let pad = " ".repeat(indent);
            for child in node.children() {
                render_node(child, &mut inner, base_dir, &inner_config, 0, false)?;
            }
            // Block children end with a blank separator line, and headings start with
            // one; don't draw either as an empty quote line at the edges of the quote.
            for line in inner.trim_matches('\n').lines() {
                // Inline resets (\x1b[0m) would end the quote's italics; re-apply after each.
                let line = line
                    .replace("\x1b[0m", "\x1b[0m\x1b[3m")
                    .replace("\x1b[23m", "\x1b[23m\x1b[3m");
                output.push_str(&format!("{pad}\x1b[2m│\x1b[0m \x1b[3m{line}\x1b[0m\n"));
            }
            output.push('\n');
        }

        NodeValue::CodeBlock(cb) => {
            let lang = cb.info.split_whitespace().next().unwrap_or("").to_string();
            let code = cb.literal.clone();
            drop(data);

            if lang == "mermaid" && config.mermaid {
                match render_mermaid(&code, config) {
                    Ok(img_str) => output.push_str(&img_str),
                    Err(e) => {
                        eprintln!("mdcat: mermaid render failed: {e}");
                        output.push_str(&render_code_block(&code, "", config, indent));
                        output.push_str("\x1b[2m[Install mmdc to render Mermaid diagrams: npm install -g @mermaid-js/mermaid-cli]\x1b[0m\n\n");
                    }
                }
            } else {
                output.push_str(&render_code_block(&code, &lang, config, indent));
            }
        }

        NodeValue::HtmlBlock(html) => {
            // Raw HTML can't be rendered, but its text content shouldn't be
            // lost. Show the text with tags removed; comments stay hidden.
            let text = html_block_text(&html.literal);
            drop(data);
            if !text.is_empty() {
                let width = (config.width as usize).saturating_sub(indent);
                let wrapped = word_wrap(&text, width, 0);
                let pad = " ".repeat(indent);
                for line in wrapped.lines() {
                    output.push_str(&format!("{pad}{line}\n"));
                }
                output.push('\n');
            }
        }

        NodeValue::List(list) => {
            let list_type = list.list_type;
            let tight = list.tight;
            let start = list.start;
            drop(data);

            let mut counter = start;
            for child in node.children() {
                let child_data = child.data.borrow();
                // Task items still occupy a position in an ordered list.
                let number = counter;
                counter += 1;
                let bullet = match &child_data.value {
                    NodeValue::TaskItem(checked) => {
                        if checked.symbol.is_some() { "☑".to_string() } else { "☐".to_string() }
                    }
                    _ => match list_type {
                        ListType::Bullet => "•".to_string(),
                        ListType::Ordered => format!("{number}."),
                    },
                };
                drop(child_data);
                render_list_item(child, output, base_dir, config, indent, tight, &bullet)?;
            }
            if !in_tight_list {
                output.push('\n');
            }
        }

        NodeValue::Item(_) => {
            // Items are rendered by their parent List via render_list_item
            drop(data);
        }

        NodeValue::ThematicBreak => {
            drop(data);
            // Stay inside the enclosing list item's indent so the rule fits the terminal.
            let line = "─".repeat((config.width as usize).saturating_sub(indent));
            let prefix = " ".repeat(indent);
            output.push_str(&format!("{prefix}\x1b[2m{line}\x1b[0m\n\n"));
        }

        NodeValue::Table(table) => {
            let alignments = table.alignments.clone();
            drop(data);
            // Render at the width left over after the indent, then indent each line.
            let inner = Config { width: config.width.saturating_sub(indent as u16).max(1), ..config.clone() };
            let mut table_out = String::new();
            render_table(node, &mut table_out, &inner, &alignments)?;
            let pad = " ".repeat(indent);
            for line in table_out.split_inclusive('\n') {
                if line == "\n" {
                    output.push_str(line);
                } else {
                    output.push_str(&pad);
                    output.push_str(line);
                }
            }
        }

        NodeValue::FootnoteDefinition(def) => {
            let label = format!("[{}]:", def.name);
            drop(data);
            render_list_item(node, output, base_dir, config, indent, false, &label)?;
        }

        NodeValue::FrontMatter(content) => {
            let content = content.clone();
            drop(data);
            let width = config.width as usize;

            // comrak includes the --- delimiters in the content; strip them
            let body: Vec<&str> = content
                .lines()
                .filter(|l| l.trim() != "---")
                .collect();

            let sep = "─".repeat(width.min(40));
            output.push_str(&format!("\x1b[2m{sep}\x1b[0m\n"));
            for line in body {
                if line.is_empty() {
                    output.push('\n');
                } else {
                    let wrapped = word_wrap(line, width, 2);
                    output.push_str(&format!("\x1b[2m{wrapped}\x1b[0m\n"));
                }
            }
            output.push_str(&format!("\x1b[2m{sep}\x1b[0m\n\n"));
        }

        _ => {
            drop(data);
            // Fallback: render children
            for child in node.children() {
                render_node(child, output, base_dir, config, indent, in_tight_list)?;
            }
        }
    }

    Ok(())
}

fn render_inline<'a>(
    node: &'a AstNode<'a>,
    output: &mut String,
    base_dir: Option<&Path>,
    config: &Config,
) -> Result<()> {
    let data = node.data.borrow();

    match &data.value {
        NodeValue::Text(text) => {
            output.push_str(text);
            drop(data);
        }

        NodeValue::SoftBreak => {
            output.push(' ');
            drop(data);
        }

        NodeValue::FootnoteReference(reference) => {
            let name = reference.name.clone();
            drop(data);
            output.push_str(&format!("\x1b[2m[{name}]\x1b[0m"));
        }

        NodeValue::LineBreak => {
            output.push('\n');
            drop(data);
        }

        // `<br>` is the usual way to break a line inside a table cell or list
        // item; treat it like a hard line break instead of dropping it.
        NodeValue::HtmlInline(html) if is_br_tag(html) => {
            drop(data);
            output.push('\n');
        }

        NodeValue::Strong => {
            drop(data);
            // Switch off only bold so enclosing styles stay active.
            render_styled_span(node, output, base_dir, config, "\x1b[1m", "\x1b[22m")?;
        }

        NodeValue::Emph => {
            drop(data);
            render_styled_span(node, output, base_dir, config, "\x1b[3m", "\x1b[23m")?;
        }

        NodeValue::Strikethrough => {
            drop(data);
            render_styled_span(node, output, base_dir, config, "\x1b[9m", "\x1b[29m")?;
        }

        NodeValue::Code(code) => {
            let text = code.literal.clone();
            drop(data);
            output.push_str(&format!("\x1b[48;5;236m\x1b[96m {text} \x1b[49m\x1b[39m"));
        }

        NodeValue::Link(link) => {
            let url = link.url.clone();
            drop(data);
            let mut label = String::new();
            for child in node.children() {
                render_inline(child, &mut label, base_dir, config)?;
            }
            let mut plain = String::new();
            collect_text(node, &mut plain);
            output.push_str(&osc8_link_for(&url, &label, &plain));
        }

        NodeValue::Image(img) => {
            let url = img.url.clone();
            drop(data);
            let mut alt = String::new();
            collect_text(node, &mut alt);

            if config.images {
                match render_image(&url, &alt, base_dir, config) {
                    Ok(img_str) => output.push_str(&img_str),
                    Err(e) => {
                        eprintln!("mdcat: image render failed ({url}): {e}");
                        output.push_str(&format!("\x1b[2m[image: {alt}]\x1b[0m"));
                    }
                }
            } else {
                output.push_str(&format!("\x1b[2m[image: {alt}]\x1b[0m"));
            }
        }

        _ => {
            drop(data);
            for child in node.children() {
                render_inline(child, output, base_dir, config)?;
            }
        }
    }

    Ok(())
}

/// Render an inline span's children between `on` and `off` SGR codes.
///
/// Links, footnote references and image placeholders end with a full reset
/// (`\x1b[0m`), which would also cancel this span's style for the rest of it;
/// re-apply `on` after each such reset.
fn render_styled_span<'a>(
    node: &'a AstNode<'a>,
    output: &mut String,
    base_dir: Option<&Path>,
    config: &Config,
    on: &str,
    off: &str,
) -> Result<()> {
    let mut inner = String::new();
    for child in node.children() {
        render_inline(child, &mut inner, base_dir, config)?;
    }
    output.push_str(on);
    output.push_str(&inner.replace("\x1b[0m", &format!("\x1b[0m{on}")));
    output.push_str(off);
    Ok(())
}

fn render_list_item<'a>(
    node: &'a AstNode<'a>,
    output: &mut String,
    base_dir: Option<&Path>,
    config: &Config,
    parent_indent: usize,
    tight: bool,
    bullet: &str,
) -> Result<()> {
    // Content hangs under the text after the marker, so wider markers ("1.", "10.") indent more.
    let indent = parent_indent + display_width(bullet) + 1;
    let prefix = " ".repeat(parent_indent);
    output.push_str(&format!("{prefix}\x1b[1m{bullet}\x1b[0m "));

    for (i, child) in node.children().enumerate() {
        let mut child_out = String::new();
        render_node(child, &mut child_out, base_dir, config, indent, tight)?;
        // The bullet already occupies the first child's indent; don't pad it twice.
        if i == 0 {
            if let Some(rest) = child_out.strip_prefix(&" ".repeat(indent)) {
                output.push_str(rest);
                continue;
            }
        }
        output.push_str(&child_out);
    }

    // An empty item has no children, so nothing ended the bullet's line.
    if !output.ends_with('\n') {
        output.push('\n');
    }

    Ok(())
}

fn render_code_block(code: &str, lang: &str, config: &Config, indent: usize) -> String {
    // The trailing newline would otherwise render as an extra empty row, and a
    // trailing CR (from CRLF files) would be printed before the closing reset.
    let highlighted = highlight_code(code.trim_end_matches(['\n', '\r']), lang, &config.theme);
    let width = (config.width as usize).saturating_sub(indent);
    let inner = width.min(60);
    let line = "─".repeat(inner);
    let lang_label = if lang.is_empty() { String::new() } else { format!(" {lang} ") };
    // The label replaces part of the top border so both borders are equally wide.
    let top_line = "─".repeat(inner.saturating_sub(lang_label.chars().count()));

    let pad = " ".repeat(indent);
    let mut out = String::new();
    out.push_str(&format!("{pad}\x1b[2m┌{lang_label}{top_line}┐\x1b[0m\n"));
    for line_str in highlighted.lines() {
        out.push_str(&format!("{pad}\x1b[2m│\x1b[0m {line_str}\n"));
    }
    out.push_str(&format!("{pad}\x1b[2m└{line}┘\x1b[0m\n\n"));
    out
}

fn render_table<'a>(
    node: &'a AstNode<'a>,
    output: &mut String,
    config: &Config,
    alignments: &[TableAlignment],
) -> Result<()> {
    // Collect rows
    let mut rows: Vec<Vec<String>> = Vec::new();

    for row in node.children() {
        let mut cells: Vec<String> = Vec::new();
        for cell in row.children() {
            let mut cell_text = String::new();
            collect_text(cell, &mut cell_text);
            cells.push(cell_text);
        }
        rows.push(cells);
    }

    if rows.is_empty() {
        return Ok(());
    }

    // Calculate column widths
    let cols = rows.iter().map(|r| r.len()).max().unwrap_or(0);
    let mut col_widths: Vec<usize> = vec![0; cols];
    for row in &rows {
        for (i, cell) in row.iter().enumerate() {
            col_widths[i] = col_widths[i].max(display_width(cell));
        }
    }

    // Shrink columns (wrapping their text) until the table fits the terminal.
    // Stacked layout is only a last resort when even the minimum widths don't fit.
    let Some(col_widths) = fit_column_widths(&rows, col_widths, config.width as usize) else {
        render_stacked_table(&rows, output, config.width as usize, alignments);
        return Ok(());
    };

    let sep: String = col_widths.iter().map(|w| "─".repeat(w + 2)).collect::<Vec<_>>().join("┼");
    let top: String = col_widths.iter().map(|w| "─".repeat(w + 2)).collect::<Vec<_>>().join("┬");
    let bot: String = col_widths.iter().map(|w| "─".repeat(w + 2)).collect::<Vec<_>>().join("┴");

    output.push_str(&format!("\x1b[2m┌{top}┐\x1b[0m\n"));

    for (i, row) in rows.iter().enumerate() {
        let wrapped: Vec<Vec<String>> = (0..cols)
            .map(|j| wrap_cell(row.get(j).map(String::as_str).unwrap_or(""), col_widths[j]))
            .collect();
        let height = wrapped.iter().map(Vec::len).max().unwrap_or(1);

        for line_idx in 0..height {
            let cells: String = wrapped.iter().enumerate().map(|(j, lines)| {
                let text = lines.get(line_idx).map(String::as_str).unwrap_or("");
                let align = alignments.get(j).copied().unwrap_or(TableAlignment::None);
                if i == 0 {
                    format!(" \x1b[1m{}\x1b[0m ", pad_aligned(text, col_widths[j], align))
                } else {
                    format!(" {} ", pad_aligned(text, col_widths[j], align))
                }
            }).collect::<Vec<_>>().join("\x1b[2m│\x1b[0m");

            output.push_str(&format!("\x1b[2m│\x1b[0m{cells}\x1b[2m│\x1b[0m\n"));
        }

        if i == 0 {
            output.push_str(&format!("\x1b[2m├{sep}┤\x1b[0m\n"));
        }
    }

    output.push_str(&format!("\x1b[2m└{bot}┘\x1b[0m\n\n"));
    Ok(())
}

/// Widest a column's minimum may be: long unbroken words are hard-broken beyond this.
const MAX_MIN_COL_WIDTH: usize = 12;

/// Shrink `widths` so the whole table (borders and padding included) fits in
/// `total` columns. Returns `None` if even the minimum widths don't fit.
fn fit_column_widths(rows: &[Vec<String>], mut widths: Vec<usize>, total: usize) -> Option<Vec<usize>> {
    let cols = widths.len();
    // left border + one separator per column + 2 padding per column
    let overhead = 1 + cols + 2 * cols;
    let available = total.checked_sub(overhead)?;
    if widths.iter().sum::<usize>() <= available {
        return Some(widths);
    }

    let mins: Vec<usize> = (0..cols)
        .map(|j| {
            let longest_word = rows
                .iter()
                .filter_map(|r| r.get(j))
                .flat_map(|c| c.split_whitespace())
                .map(display_width)
                .max()
                .unwrap_or(1);
            longest_word.clamp(1, MAX_MIN_COL_WIDTH).min(widths[j].max(1))
        })
        .collect();
    if mins.iter().sum::<usize>() > available {
        return None;
    }

    while widths.iter().sum::<usize>() > available {
        // Shave one column off the widest column that can still shrink.
        let (idx, _) = widths
            .iter()
            .enumerate()
            .filter(|(j, w)| **w > mins[*j])
            .max_by_key(|(_, w)| **w)?;
        widths[idx] -= 1;
    }
    Some(widths)
}

/// Word-wrap a table cell to `width` display columns, hard-breaking words that
/// are wider than the column. Always returns at least one line.
fn wrap_cell(text: &str, width: usize) -> Vec<String> {
    let width = width.max(1);
    let mut lines: Vec<String> = Vec::new();
    let mut current = String::new();
    let mut current_w = 0usize;

    for word in text.split_whitespace() {
        let mut word = word;
        let mut w = display_width(word);
        // Break words that can never fit on a line of their own.
        while w > width {
            if current_w > 0 {
                lines.push(std::mem::take(&mut current));
                current_w = 0;
            }
            let mut taken = 0usize;
            let mut end = 0usize;
            for (i, ch) in word.char_indices() {
                let cw = UnicodeWidthChar::width(ch).unwrap_or(0);
                if taken + cw > width && end > 0 {
                    break;
                }
                taken += cw;
                end = i + ch.len_utf8();
            }
            lines.push(word[..end].to_string());
            word = &word[end..];
            w = display_width(word);
        }
        if word.is_empty() {
            continue;
        }
        if current_w == 0 {
            current.push_str(word);
            current_w = w;
        } else if current_w + 1 + w <= width {
            current.push(' ');
            current.push_str(word);
            current_w += 1 + w;
        } else {
            lines.push(std::mem::take(&mut current));
            current.push_str(word);
            current_w = w;
        }
    }
    if current_w > 0 || lines.is_empty() {
        lines.push(current);
    }
    lines
}

fn render_stacked_table(rows: &[Vec<String>], output: &mut String, width: usize, alignments: &[TableAlignment]) {
    let headers = &rows[0];
    let label_width = headers.iter().map(|h| display_width(h)).max().unwrap_or(0);

    // No body rows to stack: show the headers so the table isn't silently dropped.
    if rows.len() == 1 {
        for header in headers {
            output.push_str(&format!("\x1b[1m{header}\x1b[0m\n"));
        }
        output.push('\n');
        return;
    }

    // Right/centre-aligned values are padded within the widest value that still
    // fits beside the label; left-aligned values stay unpadded (no trailing spaces).
    let max_value = rows[1..].iter().flatten().map(|v| display_width(v)).max().unwrap_or(0);
    let value_width = max_value.min(width.saturating_sub(label_width + 3));

    for (i, row) in rows[1..].iter().enumerate() {
        let row_label = format!(" Row {} ", i + 1);
        let dash_total = width.saturating_sub(row_label.chars().count()).max(4);
        let left = dash_total / 2;
        let right = dash_total - left;
        output.push_str(&format!(
            "\x1b[2m{}{}{}\x1b[0m\n",
            "─".repeat(left),
            row_label,
            "─".repeat(right)
        ));

        for (j, header) in headers.iter().enumerate() {
            let value = row.get(j).map(|s| s.as_str()).unwrap_or("");
            let align = alignments.get(j).copied().unwrap_or(TableAlignment::None);
            let value = match align {
                TableAlignment::Right | TableAlignment::Center => pad_aligned(value, value_width, align),
                _ => value.to_string(),
            };
            output.push_str(&format!("\x1b[1m{}\x1b[0m : {}\n", pad_to(header, label_width), value));
        }
        output.push('\n');
    }
}

/// Collect all plain text from a node and its children.
fn collect_text<'a>(node: &'a AstNode<'a>, output: &mut String) {
    let data = node.data.borrow();
    match &data.value {
        NodeValue::Text(text) => output.push_str(text),
        NodeValue::Code(code) => output.push_str(&code.literal),
        NodeValue::SoftBreak | NodeValue::LineBreak => output.push(' '),
        NodeValue::HtmlInline(html) if is_br_tag(html) => output.push(' '),
        _ => {
            drop(data);
            for child in node.children() {
                collect_text(child, output);
            }
        }
    }
}

/// Whether an inline HTML fragment is a `<br>` tag (`<br>`, `<br/>`, `<br />`, any case).
fn is_br_tag(html: &str) -> bool {
    let Some(inner) = html.strip_prefix('<').and_then(|h| h.strip_suffix('>')) else {
        return false;
    };
    let inner = inner.strip_suffix('/').unwrap_or(inner).trim_end();
    inner.eq_ignore_ascii_case("br")
}

/// Extract the visible text of a raw HTML block: comments and tags are
/// removed and whitespace is collapsed.
fn html_block_text(html: &str) -> String {
    let mut text = String::new();
    let mut rest = html;
    while let Some(start) = rest.find('<') {
        text.push_str(&rest[..start]);
        rest = &rest[start..];
        let end = if rest.starts_with("<!--") {
            rest.find("-->").map(|i| i + 3)
        } else {
            rest.find('>').map(|i| i + 1)
        };
        match end {
            Some(e) => {
                rest = &rest[e..];
                text.push(' ');
            }
            // Unterminated tag/comment: drop the remainder.
            None => return text.split_whitespace().collect::<Vec<_>>().join(" "),
        }
    }
    text.push_str(rest);
    decode_entities(&text.split_whitespace().collect::<Vec<_>>().join(" "))
}

/// Decode HTML character references (`&amp;`, `&#169;`, `&#xA9;`) in raw
/// HTML text. Unknown or malformed references are left as written.
fn decode_entities(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(amp) = rest.find('&') {
        out.push_str(&rest[..amp]);
        rest = &rest[amp..];
        // Entity names are short; don't scan far for the terminating ';'.
        let decoded = rest[1..]
            .char_indices()
            .take(32)
            .find(|&(_, c)| c == ';')
            .and_then(|(i, _)| decode_entity(&rest[1..1 + i]).map(|c| (c, i + 2)));
        match decoded {
            Some((c, len)) => {
                out.push(c);
                rest = &rest[len..];
            }
            None => {
                out.push('&');
                rest = &rest[1..];
            }
        }
    }
    out.push_str(rest);
    out
}

/// Decode one character reference body (the text between `&` and `;`).
fn decode_entity(name: &str) -> Option<char> {
    if let Some(num) = name.strip_prefix('#') {
        let (digits, radix) = match num.strip_prefix(['x', 'X']) {
            Some(hex) => (hex, 16),
            None => (num, 10),
        };
        if digits.is_empty() || !digits.chars().all(|c| c.is_digit(radix)) {
            return None;
        }
        let code = u32::from_str_radix(digits, radix).ok()?;
        return char::from_u32(code);
    }
    let c = match name {
        "amp" => '&',
        "lt" => '<',
        "gt" => '>',
        "quot" => '"',
        "apos" => '\'',
        "nbsp" => '\u{a0}',
        "copy" => '©',
        "reg" => '®',
        "trade" => '™',
        "hellip" => '…',
        "mdash" => '—',
        "ndash" => '–',
        "middot" => '·',
        "bull" => '•',
        "laquo" => '«',
        "raquo" => '»',
        _ => return None,
    };
    Some(c)
}

/// Replace terminal control characters with U+FFFD so document content can't
/// inject escape sequences (clear screen, retitle window, OSC 52 clipboard
/// writes, fake hyperlinks, ...). Tab, line feed and carriage return are kept.
fn sanitize_control_chars(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            '\t' | '\n' | '\r' => c,
            c if c.is_control() => '\u{FFFD}',
            c => c,
        })
        .collect()
}

/// Terminal display width of plain text (wide CJK characters take two columns).
fn display_width(s: &str) -> usize {
    UnicodeWidthStr::width(s)
}

/// Pad `s` with spaces on the right up to `width` display columns.
fn pad_to(s: &str, width: usize) -> String {
    format!("{s}{}", " ".repeat(width.saturating_sub(display_width(s))))
}

/// Pad `s` to `width` display columns according to a table column alignment.
fn pad_aligned(s: &str, width: usize, align: TableAlignment) -> String {
    let gap = width.saturating_sub(display_width(s));
    match align {
        TableAlignment::Right => format!("{}{s}", " ".repeat(gap)),
        TableAlignment::Center => {
            let left = gap / 2;
            format!("{}{s}{}", " ".repeat(left), " ".repeat(gap - left))
        }
        _ => pad_to(s, width),
    }
}

/// Word-wrap text at the given width, accounting for current indent.
fn word_wrap(text: &str, width: usize, indent: usize) -> String {
    // Strip ANSI for width calculation would be complex; use a simple approach
    // that wraps on whitespace boundaries. ANSI codes don't add visual width.
    let available = width.saturating_sub(indent).max(20);
    let mut result = String::new();
    let mut line_len = 0usize;

    // Explicit newlines (hard line breaks) are preserved; each segment wraps independently.
    for (i, segment) in text.split('\n').enumerate() {
        if i > 0 {
            result.push('\n');
            result.push_str(&" ".repeat(indent));
            line_len = 0;
        }
        for word in split_words(segment) {
            // Approximate visible length (ignores ANSI codes)
            let word_len = visible_len(word);
            if line_len == 0 {
                result.push_str(word);
                line_len = word_len;
            } else if line_len + 1 + word_len > available {
                result.push('\n');
                result.push_str(&" ".repeat(indent));
                result.push_str(word);
                line_len = word_len;
            } else {
                result.push(' ');
                result.push_str(word);
                line_len += 1 + word_len;
            }
        }
    }

    result
}

const CODE_START: &str = "\x1b[48;5;236m";
const CODE_END: &str = "\x1b[49m\x1b[39m";

/// Split on whitespace, but keep an inline code span intact so runs of spaces
/// inside it are not collapsed to a single space.
fn split_words(segment: &str) -> Vec<&str> {
    let mut words = Vec::new();
    let mut rest = segment;
    let mut start: Option<usize> = None; // byte offset of the current word in `segment`
    let base = segment.as_ptr() as usize;
    while !rest.is_empty() {
        let pos = rest.as_ptr() as usize - base;
        if rest.starts_with(CODE_START) {
            start.get_or_insert(pos);
            let end = rest.find(CODE_END).map_or(rest.len(), |i| i + CODE_END.len());
            rest = &rest[end..];
            continue;
        }
        let ch = rest.chars().next().unwrap();
        if ch.is_whitespace() {
            if let Some(s) = start.take() {
                words.push(&segment[s..pos]);
            }
        } else {
            start.get_or_insert(pos);
        }
        rest = &rest[ch.len_utf8()..];
    }
    if let Some(s) = start {
        words.push(&segment[s..]);
    }
    words
}

/// Estimate visible length of a string, ignoring ANSI escape sequences.
///
/// Handles CSI sequences (`ESC [ ... final-byte`) and OSC sequences such as
/// OSC 8 hyperlinks (`ESC ] ... BEL` or `ESC ] ... ESC \`).
pub(crate) fn visible_len(s: &str) -> usize {
    let mut len = 0;
    let mut chars = s.chars().peekable();
    while let Some(ch) = chars.next() {
        if ch != '\x1b' {
            len += UnicodeWidthChar::width(ch).unwrap_or(0);
            continue;
        }
        match chars.peek() {
            Some('[') => {
                chars.next();
                for c in chars.by_ref() {
                    if ('\x40'..='\x7e').contains(&c) {
                        break;
                    }
                }
            }
            Some(']') => {
                chars.next();
                while let Some(c) = chars.next() {
                    if c == '\x07' {
                        break;
                    }
                    if c == '\x1b' {
                        chars.next_if_eq(&'\\');
                        break;
                    }
                }
            }
            _ => {
                chars.next();
            }
        }
    }
    len
}

